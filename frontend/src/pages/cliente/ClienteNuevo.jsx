import { useEffect, useRef, useState } from 'react';
import { centros, paquetes } from '../../api';
import { useAsync } from '../../hooks/useAsync.js';
import { useDocumentTitle } from '../../hooks/useDocumentTitle.js';
import { PageHeader } from '../../components/layout/PageHeader.jsx';
import { Alert } from '../../components/ui/Alert.jsx';
import { Button, LinkButton } from '../../components/ui/Button.jsx';
import { Field, Select, TextInput } from '../../components/ui/Field.jsx';
import { ErrorState, Loading, errorKind } from '../../components/ui/States.jsx';
import { CopyCodeButton } from '../../components/tracking/CopyCodeButton.jsx';
import { TrackingCode } from '../../components/tracking/TrackingCode.jsx';
import { explainError } from '../../lib/serverMessages.js';
import { isoDateFromToday, parseDecimal, positiveDecimalError } from '../../lib/numbers.js';
import { formatDate } from '../../lib/format.js';

const EMPTY = { centroDistId: '', peso: '', volumen: '', direccionDestino: '', fecha: '' };

function validate(v) {
  const e = {};
  if (!v.centroDistId) e.centroDistId = 'Elige el centro de distribución donde entregarás el paquete.';
  e.peso = positiveDecimalError(v.peso, 'el peso en kilos');
  e.volumen = positiveDecimalError(v.volumen, 'el volumen en metros cúbicos');
  const dir = v.direccionDestino.trim();
  if (!dir) e.direccionDestino = 'Ingresa la dirección de destino, con calle, número y comuna.';
  else if (dir.length > 255) e.direccionDestino = 'La dirección admite hasta 255 caracteres.';
  if (!v.fecha) e.fecha = 'Elige la fecha en que el paquete debe llegar.';
  else if (v.fecha < isoDateFromToday(1)) e.fecha = 'La fecha compromiso debe ser posterior a hoy.';
  return Object.fromEntries(Object.entries(e).filter(([, m]) => m));
}

/** Crear envío. POST /api/paquete as cliente: the owner comes from the token; the tracking code is generated by the database. */
export function ClienteNuevo() {
  useDocumentTitle('Crear envío');
  const { data: lista, error: loadError, loading, reload } = useAsync((s) => centros.listCentros(s), []);
  const [values, setValues] = useState(EMPTY);
  const [errors, setErrors] = useState({});
  const [serverError, setServerError] = useState(null);
  const [busy, setBusy] = useState(false);
  const [created, setCreated] = useState(null);
  const resultRef = useRef(null);
  const errorRef = useRef(null);

  useEffect(() => { if (created) resultRef.current?.focus(); }, [created]);
  useEffect(() => { if (serverError) errorRef.current?.focus(); }, [serverError]);

  const set = (name) => (e) => {
    setValues((v) => ({ ...v, [name]: e.target.value }));
    setErrors((er) => ({ ...er, [name]: undefined }));
  };

  const submit = async (e) => {
    e.preventDefault();
    const found = validate(values);
    setErrors(found);
    setServerError(null);
    if (Object.keys(found).length) {
      requestAnimationFrame(() => document.querySelector('form [aria-invalid="true"]')?.focus());
      return;
    }
    setBusy(true);
    try {
      let pkg = await paquetes.createPaquete({
        centroDistId: Number(values.centroDistId),
        peso: parseDecimal(values.peso),
        volumen: parseDecimal(values.volumen),
        direccionDestino: values.direccionDestino.trim(),
        fechaCompromiso: `${values.fecha}T23:59:00`,
      });
      if (!pkg.codigo) pkg = await paquetes.getPaquete(pkg.paqueteId); // the code is assigned by the database
      setCreated(pkg);
    } catch (err) {
      setServerError(explainError(err));
    } finally {
      setBusy(false);
    }
  };

  const reset = () => { setValues(EMPTY); setErrors({}); setServerError(null); setCreated(null); };

  if (created) {
    return (
      <div className="page">
        <PageHeader title="Envío creado" eyebrow="Crear envío" />
        <section className="created" aria-labelledby="created-title">
          <h2 id="created-title" className="sr-only">Código de seguimiento generado</h2>
          <div ref={resultRef} tabIndex={-1} className="focus-target" aria-live="polite">
            <p className="eyebrow">Código de seguimiento</p>
            <p className="created-code"><TrackingCode code={created.codigo} variant="full" /></p>
          </div>
          <p>
            Guarda este código: con él puedes revisar por dónde va tu paquete. Compromiso de entrega:{' '}
            <strong className="mono">{formatDate(created.fechaCompromiso)}</strong>.
          </p>
          <div className="form-actions">
            <CopyCodeButton value={created.codigo} />
            <LinkButton to={`/rastreo/${encodeURIComponent(created.codigo)}`} variant="primary" icon="route">Rastrear este envío</LinkButton>
            <LinkButton to={`/cliente/envios/${created.paqueteId}`}>Ver detalle</LinkButton>
            <Button variant="ghost" onClick={reset}>Crear otro envío</Button>
          </div>
        </section>
      </div>
    );
  }

  return (
    <div className="page">
      <PageHeader title="Crear envío" eyebrow="Nuevo paquete">
        Registra el paquete y recibe un código de seguimiento al instante.
      </PageHeader>

      {loading && <Loading label="Cargando centros de distribución" />}
      {loadError && (
        <ErrorState kind={errorKind(loadError)} title="No pudimos cargar los centros" message={loadError.message} action={{ label: 'Reintentar', onClick: reload }} />
      )}

      {lista && (
        <form className="form form-narrow" onSubmit={submit} noValidate>
          {serverError && (
            <Alert ref={errorRef} tone="danger" title="No se pudo crear el envío" detail={serverError.detail}>
              {serverError.message}
            </Alert>
          )}
          <div className="form-grid">
            <Field label="Centro de distribución" required error={errors.centroDistId} hint="Donde se recibe y despacha tu paquete." className="field-wide">
              <Select value={values.centroDistId} onChange={set('centroDistId')}>
                <option value="">Elige un centro</option>
                {lista.map((c) => <option key={c.centroDistId} value={c.centroDistId}>{c.nombre} · {c.ciudad}</option>)}
              </Select>
            </Field>
            <Field label="Peso (kg)" required error={errors.peso} hint="Por ejemplo 2,5">
              <TextInput inputMode="decimal" autoComplete="off" value={values.peso} onChange={set('peso')} />
            </Field>
            <Field label="Volumen (m³)" required error={errors.volumen} hint="Por ejemplo 0,05">
              <TextInput inputMode="decimal" autoComplete="off" value={values.volumen} onChange={set('volumen')} />
            </Field>
            <Field label="Dirección de destino" required error={errors.direccionDestino} className="field-wide">
              <TextInput autoComplete="street-address" maxLength={255} value={values.direccionDestino} onChange={set('direccionDestino')} />
            </Field>
            <Field label="Fecha compromiso" required error={errors.fecha} hint="Día límite de entrega. Debe ser posterior a hoy.">
              <TextInput type="date" min={isoDateFromToday(1)} value={values.fecha} onChange={set('fecha')} />
            </Field>
          </div>
          <div className="form-actions">
            <Button type="submit" variant="primary" loading={busy}>Crear envío</Button>
            <LinkButton to="/cliente">Cancelar</LinkButton>
          </div>
        </form>
      )}
    </div>
  );
}
